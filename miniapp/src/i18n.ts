export type Lang = "uz" | "ru";
export type Key = keyof typeof uz;
const dicts: Record<Lang, Dict> = { uz, ru };

function pluralForm(lang: Lang, n: number, forms: string[]): string {
  if (lang !== "ru" || forms.length < 3) return forms[0];
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return forms[0];
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return forms[1];
  return forms[2];
}

type Params = Record<string, unknown>;

/** "{n}" substitutes a param; "{n|form1|form2|form5}" picks a (Russian) plural form for param n. */
export function translate(lang: Lang, key: string, params: Params = {}): string {
  const d = dicts[lang] as Record<string, string>;
  const text = d[key] ?? (uz as Record<string, string>)[key] ?? key;
  return text.replace(/\{(\w+)(\|[^}]*)?\}/g, (whole, k: string, forms?: string) => {
    const v = params[k];
    if (v === undefined || v === null) return whole;
    if (forms) return pluralForm(lang, Number(v), forms.slice(1).split("|"));
    return String(v);
  });
}

export function errorText(lang: Lang, code: string, params: Params = {}): string {
  let key = `err.${code}`;
  if (code === "invalid_code" && params.attempts_left === undefined) key = "err.invalid_code_bare";
  const text = translate(lang, key, params);
  return text === key ? translate(lang, "err.generic") : text;
}
